def __getattr__(name: str) -> bool:
    """Compatibility availability flags use bounded probes on explicit access."""
    from gnn.utils.runtime_safety.framework_availability import check_framework

    if name in {"DISCOPY_AVAILABLE", "JAX_FULLY_OPERATIONAL"}:
        framework = "discopy" if name == "DISCOPY_AVAILABLE" else "jax"
        return check_framework(framework, logger=logger).available
    if name == "MATPLOTLIB_AVAILABLE":
        import sys

        from gnn.execute.subprocess_envelope import run_subprocess_envelope

        return bool(
            run_subprocess_envelope(
                [sys.executable, "-c", "import matplotlib"],
                timeout=30,
                sandbox=False,
            )["success"]
        )
    raise AttributeError(name)


def execute_discopy_script(
    script_path: Path,
    verbose: bool = False,
    output_dir: Optional[Path] = None,
    timeout: int = 300,
) -> bool:
    """
    Execute a single DisCoPy Python script with syntax validation and log persistence.

    Matches the execution pattern of execute_jax_script() and execute_rxinfer_script()
    for cross-framework consistency (E-3/D-1).

    Args:
        script_path: Path to the DisCoPy Python script
        verbose: Enable verbose output logging
        output_dir: Directory for execution logs
        timeout: Execution timeout in seconds (default: 300)

    Returns:
        bool: True if execution was successful, False otherwise
    """
    import time as time_mod

    from gnn.execute.executor import execute_script_safely

    if not script_path.exists():
        logger.error(f"Script file not found: {script_path}")
        return False

    logger.info(f"Executing DisCoPy script: {script_path}")

    from gnn.execute.preconditions import script_readiness

    deadline, readiness_error = script_readiness("discopy", timeout)
    if readiness_error is not None:
        logger.error(
            "DisCoPy readiness failed (%s): %s",
            readiness_error.get("reason_code") or readiness_error.get("error_type"),
            readiness_error.get("reason") or readiness_error.get("error"),
        )
        return False

    # Validate Python syntax before execution
    try:
        with open(script_path, "r") as f:
            content = f.read()
        compile(content, script_path.name, "exec")
        logger.debug(f"✅ Script syntax valid: {script_path.name}")
    except SyntaxError as e:
        logger.error(f"❌ Syntax error in {script_path.name}: {e}")
        return False

    env = os.environ.copy()
    if output_dir:
        output_dir.mkdir(parents=True, exist_ok=True)
        env["DISCOPY_OUTPUT_DIR"] = str(output_dir.resolve())

    # Delegate the subprocess envelope (run + timing + error normalization) to
    # the canonical safe executor. Function-local import: executor.py imports
    # this runner at module scope, so a module-level import would be circular.
    abs_script_path = script_path.resolve()
    envelope = execute_script_safely(
        abs_script_path,
        timeout=timeout,
        cwd=abs_script_path.parent,
        env=env,
        deadline_monotonic=deadline,
    )

    if envelope["return_code"] == -1 and "error" in envelope:
        # The script never ran (timeout / not-found / unexpected failure).
        # The pre-delegation envelope logged and returned without writing
        # per-script logs, so keep that behavior.
        logger.error(
            f"❌ Error executing script {script_path.name}: {envelope['error']}"
        )
        return False

    elapsed = envelope["duration_seconds"]
    success: bool = bool(envelope["success"])
    result_stdout = envelope["stdout"]
    result_stderr = envelope["stderr"]
    return_code = envelope["return_code"]

    if success:
        logger.info(
            f"✅ Script executed successfully: {script_path.name} ({elapsed:.1f}s)"
        )
        if verbose and result_stdout.strip():
            logger.debug(f"Output from {script_path.name}:\n{result_stdout}")
    else:
        logger.error(f"❌ Script execution failed: {script_path.name}")
        logger.error(f"Return code: {return_code}")
        if result_stderr.strip():
            logger.error(f"Error output:\n{result_stderr}")

    # Save execution logs
    log_dir = output_dir if output_dir else abs_script_path.parent
    try:
        log_dir.mkdir(parents=True, exist_ok=True)

        execution_log: dict[str, Any] = {
            "script": str(abs_script_path),
            "return_code": return_code,
            "success": success,
            "elapsed_seconds": round(elapsed, 2),
            "timeout": timeout,
            "timestamp": time_mod.strftime("%Y-%m-%d %H:%M:%S"),
        }

        log_file = log_dir / "execution_log.json"
        with open(log_file, "w") as f:
            json.dump(execution_log, f, indent=2)

        logger.debug(f"Execution logs saved to: {log_dir}")
    except Exception as log_err:
        logger.warning(f"Could not save execution logs: {log_err}")

    return success


class DisCoPyExecutor:
    """
    DisCoPy Executor for validating and analyzing rendered DisCoPy diagrams.
    """

    def __init__(self, verbose: bool = False) -> None:
        """
        Initialize the DisCoPy executor.

        Args:
            verbose: Enable verbose logging
        """
        self.verbose = verbose
        if verbose:
            logger.setLevel(logging.DEBUG)

    def validate_diagram(self, diagram_path: Path) -> Tuple[bool, str]:
        """
        Validate that a DisCoPy diagram file exists and is accessible.

        Args:
            diagram_path: Path to the diagram file

        Returns:
            Tuple of (success: bool, message: str)
        """
        if not diagram_path.exists():
            return False, f"Diagram file not found: {diagram_path}"

        if diagram_path.suffix.lower() not in [".png", ".jpg", ".jpeg", ".svg"]:
            return False, f"Unexpected diagram file format: {diagram_path.suffix}"

        try:
            # Check if the file is readable and has content
            file_size = diagram_path.stat().st_size
            if file_size == 0:
                return False, f"Diagram file is empty: {diagram_path}"

            logger.debug(f"Validated diagram file: {diagram_path} ({file_size} bytes)")
            return True, "Diagram file validated successfully"

        except Exception as e:
            return False, f"Error validating diagram file: {e}"

    def analyze_jax_output(
        self, jax_output_path: Path
    ) -> Tuple[bool, str, Dict[str, Any]]:
        """
        Analyze a JAX evaluation output file.

        Args:
            jax_output_path: Path to the JAX evaluation output

        Returns:
            Tuple of (success: bool, message: str, analysis: Dict)
        """
        if not jax_output_path.exists():
            return False, f"JAX output file not found: {jax_output_path}", {}

        analysis: dict[str, Any] = {
            "file_path": str(jax_output_path),
            "file_size_bytes": 0,
            "file_type": jax_output_path.suffix.lower(),
            "validation_status": "unknown",
        }

        try:
            file_size = jax_output_path.stat().st_size
            analysis["file_size_bytes"] = file_size

            if file_size == 0:
                analysis["validation_status"] = "empty"
                return False, f"JAX output file is empty: {jax_output_path}", analysis

            # For image files, just validate they exist and have content
            if jax_output_path.suffix.lower() in [".png", ".jpg", ".jpeg"]:
                analysis["validation_status"] = "valid_image"
                return True, "JAX output image validated successfully", analysis

            # For other files, try to read and analyze content
            analysis["validation_status"] = "valid_file"
            logger.debug(f"Analyzed JAX output: {jax_output_path} ({file_size} bytes)")
            return True, "JAX output file analyzed successfully", analysis

        except Exception as e:
            analysis["validation_status"] = "error"
            analysis["error"] = str(e)
            return False, f"Error analyzing JAX output: {e}", analysis

    def execute_directory(self, target_dir: Path, output_dir: Path) -> Dict[str, Any]:
        """
        Execute validation and analysis on all DisCoPy outputs in a directory.

        Args:
            target_dir: Directory containing rendered DisCoPy outputs
            output_dir: Directory for execution results

        Returns:
            Dictionary with execution results
        """
        results: dict[str, Any] = {
            "executions": [],
            "successes": 0,
            "failures": 0,
            "analysis_summary": {
                "diagrams_validated": 0,
                "jax_outputs_analyzed": 0,
                "total_files_processed": 0,
            },
        }

        if not target_dir.exists():
            logger.warning(f"Target directory does not exist: {target_dir}")
            return results

        # Create output directory
        output_dir.mkdir(parents=True, exist_ok=True)

        # Find DisCoPy diagram files
        diagram_files: list[Any] = []
        jax_files: list[Any] = []

        # Look for common DisCoPy output patterns
        for pattern in ["*_diagram.png", "*_diagram.jpg", "*_diagram.svg"]:
            diagram_files.extend(target_dir.glob(f"**/{pattern}"))

        for pattern in [
            "*_jax_evaluation.png",
            "*_jax_evaluation.jpg",
            "*_evaluation*.png",
        ]:
            jax_files.extend(target_dir.glob(f"**/{pattern}"))

        logger.info(
            f"Found {len(diagram_files)} diagram files and {len(jax_files)} JAX output files"
        )

        # Validate diagram files
        for diagram_file in diagram_files:
            try:
                success, message = self.validate_diagram(diagram_file)

                execution_result: dict[str, Any] = {
                    "script": diagram_file.name,
                    "type": "diagram_validation",
                    "status": "SUCCESS" if success else "FAILED",
                    "message": message,
                    "file_path": str(diagram_file),
                }

                results["executions"].append(execution_result)

                if success:
                    results["successes"] += 1
                    results["analysis_summary"]["diagrams_validated"] += 1
                else:
                    results["failures"] += 1

                results["analysis_summary"]["total_files_processed"] += 1

            except Exception as e:
                logger.error(f"Error processing diagram {diagram_file}: {e}")
                results["failures"] += 1
                results["executions"].append(
                    {
                        "script": diagram_file.name,
                        "type": "diagram_validation",
                        "status": "ERROR",
                        "message": str(e),
                        "file_path": str(diagram_file),
                    }
                )

        # Analyze JAX output files
        for jax_file in jax_files:
            try:
                success, message, analysis = self.analyze_jax_output(jax_file)

                execution_result = {
                    "script": jax_file.name,
                    "type": "jax_analysis",
                    "status": "SUCCESS" if success else "FAILED",
                    "message": message,
                    "file_path": str(jax_file),
                    "analysis": analysis,
                }

                results["executions"].append(execution_result)

                if success:
                    results["successes"] += 1
                    results["analysis_summary"]["jax_outputs_analyzed"] += 1
                else:
                    results["failures"] += 1

                results["analysis_summary"]["total_files_processed"] += 1

            except Exception as e:
                logger.error(f"Error processing JAX output {jax_file}: {e}")
                results["failures"] += 1
                results["executions"].append(
                    {
                        "script": jax_file.name,
                        "type": "jax_analysis",
                        "status": "ERROR",
                        "message": str(e),
                        "file_path": str(jax_file),
                    }
                )

        # Save execution report
        report_file = output_dir / "discopy_execution_report.json"
        try:
            with open(report_file, "w") as f:
                json.dump(results, f, indent=2)
            logger.info(f"DisCoPy execution report saved to: {report_file}")
        except Exception as e:
            logger.error(f"Failed to save execution report: {e}")

        return results


def run_discopy_analysis(
    rendered_simulators_dir: Union[str, Path],
    execution_output_dir: Optional[Union[str, Path]] = None,
    recursive_search: bool = True,
    verbose: bool = False,
    timeout: Optional[int] = None,
) -> bool:
    """
    Find and analyze all DisCoPy outputs in the designated directory.

    Args:
        rendered_simulators_dir: Directory containing rendered simulators (target_dir from executor)
        execution_output_dir: Specific directory for DisCoPy execution outputs (optional)
        recursive_search: Whether to search recursively for outputs
        verbose: Whether to enable verbose output
        timeout: Optional per-script execution timeout in seconds. The
            analysis lane spawns no subprocesses (diagram validation and
            output analysis only); this parameter is accepted so every
            registry runner shares one invocation contract. The
            script-execution lane (``execute_discopy_script``) keeps its
            own 300 s default.

    Returns:
        bool: True if analysis completed successfully, False if any failed
    """
    # Set up execution output directory
    if execution_output_dir:
        exec_output_dir = Path(execution_output_dir)
        exec_output_dir.mkdir(parents=True, exist_ok=True)
        logger.info(f"DisCoPy execution outputs will be saved to: {exec_output_dir}")
        results_dir = exec_output_dir
    else:
        results_dir = (
            Path(rendered_simulators_dir) / "execution_results" / "discopy_results"
        )

    # Construct the path to the DisCoPy outputs
    discopy_dir = Path(rendered_simulators_dir) / "discopy"

    logger.info(f"Looking for DisCoPy outputs in: {discopy_dir}")

    if not discopy_dir.exists():
        logger.info("No DisCoPy output directory found")
        return True  # Not an error, just nothing to do

    # Create executor and run analysis
    executor = DisCoPyExecutor(verbose=verbose)
    results = executor.execute_directory(discopy_dir, results_dir)

    # Report analysis results
    total_processed = results["analysis_summary"]["total_files_processed"]
    successes = results["successes"]
    failures = results["failures"]

    logger.info(
        f"DisCoPy analysis summary: {successes} succeeded, {failures} failed, {total_processed} total"
    )

    # Preserve successes while requiring every selected artifact to succeed
    return cast("bool", failures == 0)


if __name__ == "__main__":
    # Setup logging for standalone execution
    import sys

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
        stream=sys.stdout,
    )

    # Parse command-line arguments for standalone execution
    import argparse

    parser = argparse.ArgumentParser(
        description="Analyze DisCoPy outputs generated by the GNN rendering step"
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default="../output",
        help="Main pipeline output directory",
    )
    parser.add_argument(
        "--recursive",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Recursively search for outputs in the output directory",
    )
    parser.add_argument(
        "--verbose",
        action=argparse.BooleanOptionalAction,
        default=False,
        help="Enable verbose output",
    )

    args = parser.parse_args()

    # Enable verbose logging if requested
    if args.verbose:
        logger.setLevel(logging.DEBUG)

    # Run the analysis
    success = run_discopy_analysis(
        rendered_simulators_dir=args.output_dir,
        recursive_search=args.recursive,
        verbose=args.verbose,
    )

    # Exit with appropriate status code
    sys.exit(0 if success else 1)
