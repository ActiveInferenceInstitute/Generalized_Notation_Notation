#!/usr/bin/env python3
"""
RxInfer.jl script execution module for the GNN Processing Pipeline.

This module provides functions to execute RxInfer.jl scripts that were
generated by the GNN rendering step (11_render.py).
"""

import logging
import sys
from pathlib import Path
from typing import Any, List, Optional, Union

logger = logging.getLogger(__name__)

from gnn.execute.julia_env import julia_subprocess_env
from gnn.execute.julia_setup import is_julia_available
from gnn.execute.security_gate import check_script_allowed
from gnn.execute.subprocess_envelope import CancelToken, run_subprocess_envelope


def find_rxinfer_scripts(
    base_dir: Union[str, Path], recursive: bool = True
) -> List[Path]:
    """
    Find RxInfer.jl scripts in the specified directory.

    Args:
        base_dir: Directory to search for RxInfer.jl scripts
        recursive: Whether to search recursively in subdirectories

    Returns:
        List of paths to RxInfer.jl script files
    """
    base_path = Path(base_dir)
    if not base_path.exists():
        logger.warning(f"Directory not found: {base_path}")
        return []

    # Look for both .jl files and .toml configuration files
    jl_files = list(base_path.glob("**/*.jl" if recursive else "*.jl"))
    toml_files = list(
        base_path.glob("**/*_config.toml" if recursive else "*_config.toml")
    )

    # Filter to only include RxInfer scripts (typically with _rxinfer.jl suffix)
    rxinfer_jl_files = [f for f in jl_files if "_rxinfer.jl" in f.name]

    logger.info(
        f"Found {len(rxinfer_jl_files)} RxInfer.jl scripts and {len(toml_files)} TOML configuration files in {base_path}"
    )

    # Return both script files and configuration files
    return rxinfer_jl_files + toml_files


def execute_rxinfer_script(
    script_path: Path,
    verbose: bool = False,
    output_dir: Optional[Path] = None,
    timeout: int = 300,
    *,
    cancel_token: Optional[CancelToken] = None,
) -> bool:
    """Execute a single RxInfer.jl script.

    Args:
        script_path: Path to the RxInfer.jl script or TOML configuration.
        verbose: Whether to enable verbose output.
        output_dir: Directory for execution evidence ({stem}_stdout.txt,
            {stem}_stderr.txt, {stem}_execution_log.json). Defaults to the
            script's own directory when omitted. Evidence is written on every
            completed run — success, failure, and timeout alike.
        timeout: Execution timeout in seconds (default: 300).
        cancel_token: Optional cooperative cancellation token threaded into
            the subprocess envelope (aborts the Julia process on cancel).
        The subprocess runs with the shared Julia environment:
        ``GKSwstype=100`` headless-GR default (a caller-set ``GKSwstype``
        wins).

    Returns:
        bool: True if execution was successful, False otherwise.
    """
    if not script_path.exists():
        logger.error(f"Script file not found: {script_path}")
        return False

    logger.info(f"Executing RxInfer script: {script_path}")

    # E-2: Validate Julia syntax before execution
    if script_path.suffix.lower() == ".jl":
        try:
            with open(script_path, "r", encoding="utf-8") as f:
                content = f.read()
            if not content.strip():
                logger.error(f"Script file is empty: {script_path}")
                return False
            logger.debug(
                f"✅ Julia script readable: {script_path.name} ({len(content)} bytes)"
            )
        except (OSError, UnicodeError) as exc:
            logger.error(
                "Could not read script %s (%s: %s)",
                script_path,
                type(exc).__name__,
                exc,
            )
            return False

    # Different handling based on file type
    if script_path.suffix.lower() == ".jl":
        # For Julia files, run with the committed RxInfer project environment
        rxinfer_project = Path(__file__).parent.resolve()
        cmd: list[Any] = [
            "julia",
            "--startup-file=no",
            f"--project={rxinfer_project}",
            str(script_path),
        ]
        # The spawned program for this branch is the rendered script itself.
        program_to_gate = script_path
    elif script_path.suffix.lower() == ".toml":
        # For TOML configuration files, we need a Julia script that can load and run them
        # This would typically be a standard RxInfer.jl script that takes a config file as input

        # Look for a rxinfer_runner.jl script in the same directory as this Python file
        runner_script = Path(__file__).parent / "rxinfer_runner.jl"
        if not runner_script.exists():
            logger.error(f"RxInfer.jl runner script not found: {runner_script}")
            logger.error("Cannot execute TOML configuration without a runner script")
            return False
        # TOML configs are gate-exempt argv data for the committed runner;
        # the scanned program on this branch is rxinfer_runner.jl itself.
        program_to_gate = runner_script

        # Same committed RxInfer project environment as the .jl branch —
        # the TOML runner needs `using RxInfer` to resolve packages.
        rxinfer_project = Path(__file__).parent.resolve()
        cmd = [
            "julia",
            "--startup-file=no",
            f"--project={rxinfer_project}",
            str(runner_script),
            str(script_path),
        ]
    else:
        logger.error(f"Unsupported file type: {script_path.suffix}")
        return False
    # Shared pre-execution security gate (fail closed; GNN_ALLOW_UNSAFE_EXEC
    # is the only operator opt-out), applied to the program this command
    # spawns: the rendered script for .jl inputs, the committed
    # rxinfer_runner.jl for TOML configs (whose config file is argv data,
    # not the scanned program).
    gate_verdict = check_script_allowed(program_to_gate)
    if gate_verdict["overridden"]:
        logger.warning(
            "GNN_ALLOW_UNSAFE_EXEC set: pre-execution security gate "
            "bypassed for %s (trusted-local use only)",
            program_to_gate,
        )
    if not gate_verdict["ok"]:
        logger.error(
            "Pre-execution security gate blocked %s: %s",
            program_to_gate,
            gate_verdict["reason"],
        )
        return False

    logger.debug(f"Running command: {' '.join(cmd)}")
    # Headless GR default (GKSwstype=100); a caller-set GKSwstype wins.
    envelope = run_subprocess_envelope(
        cmd,
        timeout=timeout,
        env=julia_subprocess_env(),
        cancel_token=cancel_token,
    )

    # Process the execution result — every outcome below means the run
    # completed (success, non-zero exit, or timeout), so persistence runs
    # before returning.
    success: bool = bool(envelope["success"])
    error_type = envelope.get("error_type")

    if error_type == "TimeoutExpired":
        logger.error(
            f"❌ Script execution timed out after {timeout}s: {script_path.name}"
        )
    elif envelope["return_code"] == -1:
        logger.error(
            f"Error executing script {script_path.name}: {envelope.get('error', '')}"
        )
    elif success:
        logger.info(f"Script executed successfully: {script_path.name}")
        if verbose:
            logger.debug(f"Output from {script_path.name}:\n{envelope['stdout']}")
    else:
        logger.error(
            f"Script execution failed with return code {envelope['return_code']}: {script_path.name}"
        )
        logger.error(f"Error output:\n{envelope['stderr']}")

    # Persist execution evidence (E-1/J-1, mirrors jax_runner): reuse the
    # envelope's captured streams rather than re-capturing. Best-effort —
    # a persistence failure must never mask the run result.
    import json as json_mod
    import time as time_mod

    log_dir = output_dir if output_dir else script_path.resolve().parent
    try:
        log_dir.mkdir(parents=True, exist_ok=True)

        stdout_file = log_dir / f"{script_path.stem}_stdout.txt"
        with open(stdout_file, "w") as f:
            f.write(envelope["stdout"])

        stderr_file = log_dir / f"{script_path.stem}_stderr.txt"
        with open(stderr_file, "w") as f:
            f.write(envelope["stderr"])

        execution_log: dict[str, Any] = {
            "script": str(script_path.resolve()),
            "command": cmd,
            "return_code": envelope["return_code"],
            "success": success,
            "elapsed_seconds": round(envelope["duration_seconds"], 2),
            "timeout": timeout,
            "timestamp": time_mod.strftime("%Y-%m-%d %H:%M:%S"),
        }
        if envelope.get("error"):
            execution_log["error"] = envelope["error"]
        if error_type:
            execution_log["error_type"] = error_type

        log_file = log_dir / f"{script_path.stem}_execution_log.json"
        with open(log_file, "w") as f:
            json_mod.dump(execution_log, f, indent=2)

        logger.debug(f"Execution logs saved to: {log_dir}")
    except (OSError, UnicodeError, TypeError, ValueError) as log_err:
        logger.warning(
            "Could not save execution logs for %s in %s (%s: %s)",
            script_path,
            log_dir,
            type(log_err).__name__,
            log_err,
        )

    return success


def run_rxinfer_scripts(
    rendered_simulators_dir: Union[str, Path],
    execution_output_dir: Optional[Union[str, Path]] = None,
    recursive_search: bool = True,
    verbose: bool = False,
    timeout: Optional[int] = None,
) -> bool:
    """
    Find and run all RxInfer.jl scripts in the designated directory.

    Args:
        rendered_simulators_dir: Directory containing rendered simulators (target_dir from executor)
        execution_output_dir: Specific directory for RxInfer execution outputs (optional)
        recursive_search: Whether to search recursively for scripts
        verbose: Whether to enable verbose output
        timeout: Optional per-script execution timeout in seconds; each
            script runs with its historical 300 s default when omitted.

    Returns:
        bool: True if all scripts executed successfully, False if any failed
    """
    # Check if Julia is available
    if not is_julia_available():
        logger.error("Julia is not available, cannot execute RxInfer.jl scripts")
        return False

    # Set up execution output directory
    if execution_output_dir:
        exec_output_dir = Path(execution_output_dir)
        exec_output_dir.mkdir(parents=True, exist_ok=True)
        logger.info(f"RxInfer execution outputs will be saved to: {exec_output_dir}")

    # Construct the path to the RxInfer.jl scripts
    rxinfer_dir = Path(rendered_simulators_dir) / "rxinfer"

    logger.info(f"Looking for RxInfer.jl scripts in: {rxinfer_dir}")

    # Find all RxInfer.jl scripts
    script_files = find_rxinfer_scripts(rxinfer_dir, recursive_search)

    if not script_files:
        logger.info("No RxInfer.jl scripts found")
        return True  # Not an error, just nothing to do

    script_timeout = timeout if timeout is not None else 300

    # Execute each script
    success_count = 0
    failure_count = 0

    for script_file in script_files:
        if execute_rxinfer_script(script_file, verbose, timeout=script_timeout):
            success_count += 1
        else:
            failure_count += 1

    # Report execution results
    total_count = success_count + failure_count
    logger.info(
        f"RxInfer.jl script execution summary: {success_count} succeeded, {failure_count} failed, {total_count} total"
    )

    # Consider the overall run successful only if all scripts succeeded
    return failure_count == 0


if __name__ == "__main__":
    # Setup logging for standalone execution
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
        stream=sys.stdout,
    )

    # Parse command-line arguments for standalone execution
    import argparse

    parser = argparse.ArgumentParser(
        description="Execute RxInfer.jl scripts generated by the GNN rendering step"
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default="../output",
        help="Main pipeline output directory",
    )
    parser.add_argument(
        "--recursive",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Recursively search for scripts in the output directory",
    )
    parser.add_argument(
        "--verbose",
        action=argparse.BooleanOptionalAction,
        default=False,
        help="Enable verbose output",
    )

    args = parser.parse_args()

    # Enable verbose logging if requested
    if args.verbose:
        logger.setLevel(logging.DEBUG)

    # Run the scripts
    success = run_rxinfer_scripts(
        rendered_simulators_dir=args.output_dir,
        recursive_search=args.recursive,
        verbose=args.verbose,
    )

    # Exit with appropriate status code
    sys.exit(0 if success else 1)
