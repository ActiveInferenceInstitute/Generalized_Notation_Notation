TORCHLENS_ARTIFACTS_ENV = "GNN_TORCHLENS_ARTIFACTS"

EFE_CONVENTION = (
    "pytorch renderer efe_history:"
    " EFE = ambiguity + risk where ambiguity = -(sum_s' q(s') *"
    " sum_o A[o,s'] log A[o,s']) (expected entropy of"
    " observations) and risk = sum_o q(o) (log q(o) - log"
    " softmax(C)[o]) (KL of predicted observations against"
    " softmax-normalised preferences). Closest to the Lean"
    " expectedFreeEnergy_eq_risk_add_ambiguity shape, but the"
    " preference reference is softmax(C), not the raw C vector,"
    " so values are not directly comparable without convention"
    " mapping (bridge finding O1)."
)

POLICY_CONVENTION = (
    "pytorch renderer policy_history: one-step action distribution"
    " softmax(log E - G) with unit policy precision; E is the declared"
    " habit vector, or uniform when the specification declares none"
    " (a uniform E leaves softmax(-G) unchanged)."
)

_MODULE_DOCSTRING = """\
PyTorch POMDP Simulation: {model_name}

Auto-generated by GNN Pipeline — PyTorch renderer.
Implements the standard Active Inference generative loop with torch.nn.Module
components named after the GNN variables they compute (A, B, C, D, E, s,
s_prime, o, G, pi, u). One seeded torch.Generator drives every sample, so a
run is reproducible from RANDOM_SEED. Set GNN_TORCHLENS_CAPTURE=1 (torchlens
extra) to also record the rollout op by op with TorchLens.
"""


