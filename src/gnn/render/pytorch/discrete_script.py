def _site_of(module_address):
    """Strip the pass suffix from a TorchLens module address ('agent.efe:3')."""
    if not module_address:
        return "rollout"
    return str(module_address).rsplit(":", 1)[0]


def _site_edges(trace):
    """Count traced dataflow edges between distinct module/buffer sites."""
    buffer_sites = {label: trace[label].buffer_address for label in trace.buffer_layers}
    op_sites = {}
    for op in trace.ops:
        site = _site_of(op.module)
        op_sites[op.label] = site
        op_sites[op.label.rsplit(":", 1)[0]] = site
    counts = {}
    for op in trace.ops:
        target = op_sites[op.label]
        for parent in op.parents:
            source = buffer_sites.get(parent) or op_sites.get(parent)
            if source is None:
                source = op_sites.get(str(parent).rsplit(":", 1)[0], "input")
            if source != target:
                counts[(source, target)] = counts.get((source, target), 0) + 1
    return [[source, target, count] for (source, target), count in sorted(counts.items())]


def _agent_step_inputs(outputs):
    """Return the recorded agent inputs of the first and the last timestep."""
    beliefs, _, _, actions, observations = outputs
    step = beliefs.shape[0] - 1
    steps = {"first_step": (0, (observations[0],))}
    if step >= 1:
        steps["last_step"] = (
            step,
            (observations[step], beliefs[step - 1], actions[step - 1]),
        )
    return steps


def _validate_agent_steps(tl, rollout, outputs):
    """Perturbation-validate the deterministic agent step with tl.validate.

    TorchLens validation replays every op with perturbed parent values.
    Categorical sampling (multinomial, one_hot) rejects perturbed inputs, so
    the stochastic full rollout is checked by exact reproduction instead and
    the deterministic perception-and-planning step is validated here at the
    first timestep (prior D) and the last timestep (prior B[:, :, u] s).
    """
    return {
        name: bool(tl.validate(rollout.agent, inputs))
        for name, (_, inputs) in _agent_step_inputs(outputs).items()
    }


def _lesion_witnesses(tl, rollout, outputs):
    """Zero the ambiguity or risk term of G at the last step and record pi."""
    steps = _agent_step_inputs(outputs)
    step, inputs = steps.get("last_step", steps["first_step"])
    step_trace = tl.trace(rollout.agent, inputs)
    full = step_trace["policy"].out.detach()
    witness = {
        "timestep": int(step),
        "policy": full.tolist(),
        "argmax_action": int(full.argmax()),
        "lesions": {},
    }
    for name, site in (("no_ambiguity", "efe.ambiguity"), ("no_risk", "efe.risk")):
        lesioned = step_trace.fork().do(tl.module(site), tl.zero_ablate())
        policy = lesioned["policy"].out.detach()
        kl = float((full * (torch.log(full + EPS) - torch.log(policy + EPS))).sum())
        kl = max(kl, 0.0)  # rounding can push an exact-zero divergence below zero
        witness["lesions"][name] = {
            "site": "agent." + site,
            "edit": "zero_ablate",
            "policy": policy.tolist(),
            "argmax_action": int(policy.argmax()),
            "kl_full_to_lesioned": kl,
        }
    return witness


def _record_artifact(summary, name, relative_path, write):
    summary["artifacts"][name] = relative_path
    try:
        write()
    except Exception as exc:  # each artifact is independent evidence
        del summary["artifacts"][name]
        summary["artifact_errors"][name] = f"{type(exc).__name__}: {exc}"


def _torchlens_capture(rollout, seed, outputs, output_dir):
    """Trace the rollout with TorchLens when GNN_TORCHLENS_CAPTURE is set.

    Returns a JSON-serialisable summary stored in simulation_results.json.
    Capture is auxiliary evidence: an unavailable or failed capture records
    its reason and never alters the simulation results.
    """
    requested = os.environ.get(TORCHLENS_CAPTURE_ENV, "").strip().lower()
    if requested not in ("1", "true", "yes", "on"):
        return {"status": "disabled", "reason": TORCHLENS_CAPTURE_ENV + " is not set"}
    artifact_mode = os.environ.get(TORCHLENS_ARTIFACTS_ENV, "summary").strip().lower()
    if artifact_mode not in ("summary", "full"):
        return {
            "status": "failed",
            "reason": f"{TORCHLENS_ARTIFACTS_ENV} must be 'summary' or 'full', got {artifact_mode!r}",
        }
    try:
        import torchlens as tl
    except ImportError as exc:
        return {
            "status": "unavailable",
            "reason": f"torchlens is not importable ({exc}); install with: uv sync --extra torchlens",
        }

    started = time.time()
    capture_dir = output_dir / "torchlens"
    capture_dir.mkdir(parents=True, exist_ok=True)
    summary = {
        "status": "captured",
        "scope": "full_rollout",
        "artifact_mode": artifact_mode,
        "torchlens_version": getattr(tl, "__version__", "unknown"),
        "torch_version": torch.__version__,
        "random_seed": RANDOM_SEED,
        "declared_connections": GNN_DECLARED_CONNECTIONS,
        "variable_sites": GNN_VARIABLE_SITES,
        "unmapped_variables": GNN_UNMAPPED_VARIABLES,
        "artifacts": {},
        "artifact_errors": {},
    }
    try:
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            trace = tl.trace(rollout, seed)
            traced = [op.out for op in trace.output_ops]
            summary["num_ops"] = len(trace.ops)
            summary["trace_reproduces_simulation"] = len(traced) == len(outputs) and all(
                torch.equal(left, right) for left, right in zip(traced, outputs)
            )
            summary["agent_step_validation"] = _validate_agent_steps(tl, rollout, outputs)
            summary["validated"] = all(summary["agent_step_validation"].values())
            summary["validation_scope"] = (
                "rollout: exact reproduction of the plain run; agent step:"
                " tl.validate perturbation replay at the first and last timestep"
            )
            summary["site_edges"] = _site_edges(trace)
        warning_counts = {}
        for caught_warning in caught:
            name = caught_warning.category.__name__
            warning_counts[name] = warning_counts.get(name, 0) + 1
        # ScalarEscapeWarning is expected: StateInference reads the evidence
        # as a Python float to refuse impossible observations.
        summary["capture_warnings"] = dict(sorted(warning_counts.items()))
    except Exception as exc:
        summary["status"] = "failed"
        summary["reason"] = f"{type(exc).__name__}: {exc}"
        summary["capture_seconds"] = round(time.time() - started, 3)
        return summary

    try:
        with warnings.catch_warnings():
            # The step re-trace repeats the expected evidence scalar escape.
            warnings.simplefilter("ignore")
            summary["intervention_witnesses"] = _lesion_witnesses(tl, rollout, outputs)
    except Exception as exc:
        summary["artifact_errors"]["intervention_witnesses"] = f"{type(exc).__name__}: {exc}"

    _record_artifact(
        summary,
        "report_html",
        "torchlens/report.html",
        lambda: tl.export.html(trace, capture_dir / "report.html", graph="none"),
    )
    _record_artifact(
        summary,
        "graph_rolled_svg",
        "torchlens/rollout_rolled.svg",
        lambda: trace.draw(
            path=str(capture_dir / "rollout_rolled"),
            rolled=True,
            file_format="svg",
            direction="leftright",
        ),
    )
    if artifact_mode == "full":

        def _save_bundle():
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                trace.save(
                    capture_dir / "rollout.tlspec",
                    level="portable",
                    overwrite=True,
                    include_custom_attributes=False,
                )

        _record_artifact(summary, "tlspec", "torchlens/rollout.tlspec", _save_bundle)
        _record_artifact(
            summary,
            "ops_csv",
            "torchlens/ops.csv",
            lambda: tl.export.csv(trace, capture_dir / "ops.csv"),
        )
    summary["capture_seconds"] = round(time.time() - started, 3)
    _record_artifact(
        summary,
        "manifest",
        "torchlens/torchlens_capture.json",
        lambda: (capture_dir / "torchlens_capture.json").write_text(
            json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
        ),
    )
    return summary


# --- Simulation ----------------------------------------------------------------


def run_simulation():
    """Run POMDP simulation with PyTorch tensors."""
    start_time = time.time()
    rollout = build_rollout().eval()
    seed = torch.tensor(RANDOM_SEED)
    with torch.no_grad():
        outputs = rollout(seed)
    beliefs_t, efe_t, policy_t, actions_t, observations_t = outputs
    num_obs, num_states = rollout.agent.A.shape
    num_actions = rollout.agent.B.shape[2]
    T = rollout.num_timesteps

    beliefs_history = beliefs_t.cpu().numpy().tolist()
    efe_history = efe_t.cpu().numpy().tolist()
    policy_history = policy_t.cpu().numpy().tolist()
    actions_history = [int(index) for index in actions_t.argmax(dim=1).tolist()]
    observations_history = [int(index) for index in observations_t.argmax(dim=1).tolist()]

    elapsed = time.time() - start_time

    # --- Validation ---
    beliefs_arr = np.array(beliefs_history)
    policy_arr = np.array(policy_history)
    validation = {
        "beliefs_in_range": bool(np.all((beliefs_arr >= 0) & (beliefs_arr <= 1))),
        "beliefs_sum_to_one": bool(np.allclose(beliefs_arr.sum(axis=1), 1.0, atol=1e-6)),
        "policy_sums_to_one": bool(np.allclose(policy_arr.sum(axis=1), 1.0, atol=1e-6)),
        "actions_in_range": all(0 <= a < num_actions for a in actions_history),
        "all_valid": True
    }
    validation["all_valid"] = all(validation.values())

    output_dir = Path(os.environ.get("PYTORCH_OUTPUT_DIR", "."))
    output_dir.mkdir(parents=True, exist_ok=True)
    try:
        torchlens_summary = _torchlens_capture(rollout, seed, outputs, output_dir)
    except Exception as exc:  # capture must never change the simulation outcome
        torchlens_summary = {"status": "failed", "reason": f"{type(exc).__name__}: {exc}"}

    results = {
        "schema_version": "pytorch_simulation_v1",
        "model_name": MODEL_NAME,
        "framework": "pytorch",
        "matrix_provenance": __PROVENANCE__,
        "num_timesteps": T,
        "num_states": int(num_states),
        "num_observations": int(num_obs),
        "num_actions": int(num_actions),
        "random_seed": RANDOM_SEED,
        "beliefs": beliefs_history,
        "actions": actions_history,
        "observations": observations_history,
        "efe_history": efe_history,
        "policy_history": policy_history,
        "habit": {"source": HABIT_SOURCE, "E": rollout.agent.E.cpu().numpy().tolist()},
        "expected_free_energy_convention": __EFE_CONVENTION__,
        "policy_convention": __POLICY_CONVENTION__,
        "validation": validation,
        "execution_time_seconds": round(elapsed, 4),
        "torch_version": torch.__version__,
        "torchlens": torchlens_summary,
    }

    # Save results
    output_file = output_dir / "simulation_results.json"
    with open(output_file, "w") as f:
        json.dump(results, f, indent=2, ensure_ascii=False)

    print(f"PyTorch POMDP simulation complete: {T} timesteps in {elapsed:.3f}s")
    print(f"Results saved to: {output_file}")
    print(f"Validation: {validation}")
    print(f"TorchLens capture: {torchlens_summary['status']}")
    if not validation["all_valid"]:
        raise RuntimeError("Invalid simulation results; see the persisted validation receipt")
    return results


if __name__ == "__main__":
    run_simulation()
