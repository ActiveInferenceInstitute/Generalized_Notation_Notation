"""Emit the standalone discrete PyTorch Active Inference script.

The emitted script expresses the generative model (``agent``) and generative
process (``process``) as ``torch.nn.Module`` components whose buffers and
submodules carry GNN meanings (see :mod:`gnn.render.pytorch.sites`). The
rollout is a single connected tensor computation driven by one seeded
``torch.Generator``, so the same object can be executed plainly or traced op
by op with TorchLens.

TorchLens is optional. The script imports it only inside
``_torchlens_capture`` when ``GNN_TORCHLENS_CAPTURE`` is set, so neither the
pipeline parent nor an ordinary simulation run depends on it.
"""

from __future__ import annotations

import pprint
import re
from typing import Any, Dict, List, Mapping

