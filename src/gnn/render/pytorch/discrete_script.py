def _literal(value: Any) -> str:
    """Return a readable Python literal for emitted constant data."""
    return pprint.pformat(value, width=88, sort_dicts=True)


def generate_discrete_script(
    *,
    model_name: str,
    random_seed: int,
    num_states: int,
    num_obs: int,
    num_actions: int,
    num_timesteps: int,
    a_literal: str,
    c_literal: str,
    d_literal: str,
    e_literal: str,
    b_init: str,
    habit_source: str,
    matrix_provenance: Mapping[str, Any],
    declared_connections: List[Dict[str, str]],
    variable_sites: Mapping[str, List[str]],
    unmapped_variables: Mapping[str, str],
) -> str:
    """Return the complete discrete PyTorch script for one GNN model.

    Matrix arguments are pre-formatted ``torch.tensor`` literals; ``b_init``
    is the statement block binding ``B`` (``B_slices`` stacking or the
    expanded two-dimensional form). All other arguments are emitted as
    Python literals.
    """
    docstring = _MODULE_DOCSTRING.format(model_name=model_name)
    docstring_literal = (
        "(\n"
        + "".join(f"    {line!r}\n" for line in docstring.splitlines(keepends=True))
        + ")"
    )
    replacements = {
        "__DOCSTRING__": docstring_literal,
        "__MODEL_NAME_REPR__": repr(str(model_name)),
        "__SEED__": str(int(random_seed)),
        "__HABIT_SOURCE__": repr(habit_source),
        "__CONNECTIONS__": _literal(list(declared_connections)),
        "__VARIABLE_SITES__": _literal(dict(variable_sites)),
        "__UNMAPPED__": _literal(dict(unmapped_variables)),
        "__CAPTURE_ENV__": TORCHLENS_CAPTURE_ENV,
        "__ARTIFACTS_ENV__": TORCHLENS_ARTIFACTS_ENV,
        "__NUM_STATES__": str(int(num_states)),
        "__NUM_OBS__": str(int(num_obs)),
        "__NUM_ACTIONS__": str(int(num_actions)),
        "__T__": str(int(num_timesteps)),
        "__A__": a_literal,
        "__C__": c_literal,
        "__D__": d_literal,
        "__E__": e_literal,
        "__B_INIT__": b_init.strip(),
        "__PROVENANCE__": repr(dict(matrix_provenance)),
        "__EFE_CONVENTION__": repr(EFE_CONVENTION),
        "__POLICY_CONVENTION__": repr(POLICY_CONVENTION),
    }
    tokens = "|".join(re.escape(token) for token in replacements)
    return re.sub(tokens, lambda match: replacements[match[0]], _TEMPLATE)


