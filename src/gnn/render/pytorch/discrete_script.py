# --- Generative model (agent) -------------------------------------------------


class Transition(nn.Module):
    """Predicted next-state prior s_prime = B[:, :, u] s (GNN: s>s_prime, u>s_prime)."""

    def forward(self, B, s, u_onehot):
        return torch.tensordot(B, u_onehot, dims=([2], [0])) @ s


class StateInference(nn.Module):
    """Posterior s proportional to A[o, :] * prior (GNN: D>s, s-A, A-o)."""

    def forward(self, A, o_onehot, prior):
        joint = (o_onehot @ A) * prior
        evidence = joint.sum()
        if not np.isfinite(float(evidence)) or float(evidence) <= 0.0:
            raise RuntimeError("Observation has zero or nonfinite predictive probability")
        return joint / evidence


class Ambiguity(nn.Module):
    """Expected observation entropy for every action (epistemic term of G)."""

    def forward(self, A, predicted_states):
        return -(predicted_states * (A * torch.log(A + EPS)).sum(dim=0)).sum(dim=-1)


class Risk(nn.Module):
    """KL of predicted observations from softmax(C) for every action."""

    def forward(self, predicted_obs, C):
        log_pref = torch.log(torch.softmax(C, dim=0) + EPS)
        return (predicted_obs * (torch.log(predicted_obs + EPS) - log_pref)).sum(dim=-1)


class ExpectedFreeEnergy(nn.Module):
    """G = ambiguity + risk for every one-step action (GNN: C>G)."""

    def __init__(self):
        super().__init__()
        self.ambiguity = Ambiguity()
        self.risk = Risk()

    def forward(self, A, B, C, s):
        predicted_states = torch.einsum("ija,j->ai", B, s)
        predicted_obs = predicted_states @ A.T
        return self.ambiguity(A, predicted_states) + self.risk(predicted_obs, C)


class PolicySelection(nn.Module):
    """pi = softmax(log E - G) over one-step actions (GNN: G>pi, E>pi)."""

    def forward(self, G, E):
        return torch.softmax(torch.log(E + EPS) - G, dim=0)


class ActionSampling(nn.Module):
    """u ~ Cat(pi), returned one-hot (GNN: pi>u)."""

    def forward(self, pi, generator):
        index = torch.multinomial(pi, 1, generator=generator)[0]
        return F.one_hot(index, pi.shape[0]).to(pi.dtype)


class ActiveInferenceAgent(nn.Module):
    """Generative model: buffers A, B, C, D, E and one perception-action step."""

    def __init__(self, A, B, C, D, E):
        super().__init__()
        self.register_buffer("A", A)
        self.register_buffer("B", B)
        self.register_buffer("C", C)
        self.register_buffer("D", D)
        self.register_buffer("E", E)
        self.transition = Transition()
        self.state_inference = StateInference()
        self.efe = ExpectedFreeEnergy()
        self.policy = PolicySelection()
        self.action = ActionSampling()

    def forward(self, o_onehot, beliefs=None, u_prev_onehot=None):
        """Return (s, G, pi) for one observation; the first step uses prior D."""
        if u_prev_onehot is None:
            prior = self.D if beliefs is None else beliefs
        else:
            prior = self.transition(self.B, beliefs, u_prev_onehot)
        s = self.state_inference(self.A, o_onehot, prior)
        G = self.efe(self.A, self.B, self.C, s)
        return s, G, self.policy(G, self.E)


# --- Generative process (environment) ----------------------------------------


class InitialState(nn.Module):
    """Sample the initial true hidden state from D."""

    def forward(self, D, generator):
        index = torch.multinomial(D, 1, generator=generator)[0]
        return F.one_hot(index, D.shape[0]).to(D.dtype)


class Observation(nn.Module):
    """Sample a one-hot observation o ~ A[:, state] (GNN: A-o)."""

    def forward(self, A, state_onehot, generator):
        probs = A @ state_onehot
        probs = probs / probs.sum()
        index = torch.multinomial(probs, 1, generator=generator)[0]
        return F.one_hot(index, A.shape[0]).to(A.dtype)


class StateTransition(nn.Module):
    """Sample the next true hidden state from B[:, state, u]."""

    def forward(self, B, u_onehot, state_onehot, generator):
        probs = torch.tensordot(B, u_onehot, dims=([2], [0])) @ state_onehot
        probs = probs / (probs.sum() + EPS)
        index = torch.multinomial(probs, 1, generator=generator)[0]
        return F.one_hot(index, B.shape[0]).to(B.dtype)


class GenerativeProcess(nn.Module):
    """Environment with its own A, B and D buffers (same authored values)."""

    def __init__(self, A, B, D):
        super().__init__()
        self.register_buffer("A", A)
        self.register_buffer("B", B)
        self.register_buffer("D", D)
        self.initial_state = InitialState()
        self.observe = Observation()
        self.transition = StateTransition()


class ActiveInferenceRollout(nn.Module):
    """Agent-environment loop over num_timesteps steps, seeded by its input."""

    def __init__(self, A, B, C, D, E, num_timesteps):
        super().__init__()
        self.agent = ActiveInferenceAgent(A, B, C, D, E)
        self.process = GenerativeProcess(A.clone(), B.clone(), D.clone())
        self.num_timesteps = int(num_timesteps)

    def forward(self, seed):
        generator = torch.Generator().manual_seed(int(seed))
        true_state = self.process.initial_state(self.process.D, generator)
        beliefs = None
        u_prev = None
        history = {key: [] for key in ROLLOUT_OUTPUTS}
        for _ in range(self.num_timesteps):
            o = self.process.observe(self.process.A, true_state, generator)
            s, G, pi = self.agent(o, beliefs, u_prev)
            u = self.agent.action(pi, generator)
            true_state = self.process.transition(self.process.B, u, true_state, generator)
            history["beliefs"].append(s)
            history["efe"].append(G)
            history["policy"].append(pi)
            history["actions"].append(u)
            history["observations"].append(o)
            beliefs = s
            u_prev = u
        return tuple(torch.stack(history[key]) for key in ROLLOUT_OUTPUTS)


